#!/usr/bin/env bash
# Native build + test pass for Dinner, Together. Runs on a GitHub macOS runner
# or any Mac with Xcode. It never stops at the first failure — every step
# records its exit code so the artifact tells the whole story — but it DOES
# exit non-zero at the end if any REQUIRED step failed or could not run
# (missing simulator, app not built, tests not executed, counts short).
#
#   bash native-validation/run-native-pass.sh [results-dir]
#
# Produces: <results>/SUMMARY.md, status.txt (REQUIRED_FAILURES=n),
# environment.txt, *.log, *-cases.txt, *.xcresult.zip, ui-screenshots/<device>/,
# and the simulator app build for screenshots.sh under <results>/build.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RESULTS="${1:-$ROOT/native-validation/results}"
mkdir -p "$RESULTS"
cd "$ROOT"

SUMMARY="$RESULTS/SUMMARY.md"
STATUS="$RESULTS/status.txt"
: > "$SUMMARY"
REQUIRED_FAILURES=0
note() { printf '%s\n' "$*" | tee -a "$SUMMARY"; }
# count_matches FILE PATTERN → a single integer, never "0\n0"
count_matches() { local n; n=$(grep -c -- "$2" "$1" 2>/dev/null); printf '%s' "${n:-0}"; }
pass() { note "- ✅ $1"; }
fail() { note "- ❌ $1"; REQUIRED_FAILURES=$((REQUIRED_FAILURES + 1)); }
step_result() { # name exit_code logfile
  if [ "$2" -eq 0 ]; then pass "$1 (exit 0) — \`$(basename "$3")\`"; else fail "$1 (exit $2) — \`$(basename "$3")\`"; fi
}
finish() {
  printf 'REQUIRED_FAILURES=%s\n' "$REQUIRED_FAILURES" > "$STATUS"
  note ""
  if [ "$REQUIRED_FAILURES" -eq 0 ]; then
    note "**Result: all required steps passed.**"
  else
    note "**Result: $REQUIRED_FAILURES required step(s) failed or could not run.**"
  fi
  note ""
  note "_Generated by native-validation/run-native-pass.sh_"
  [ "$REQUIRED_FAILURES" -eq 0 ]
}

# Expected test count comes from the source, so "0 tests executed" cannot pass.
EXPECTED_TESTS=$(cat "$ROOT"/DinnerTogetherTests/*.swift | grep -c 'func test' || true)
EXPECTED_UI_IPHONE=$(count_matches "$ROOT/DinnerTogetherUITests/DinnerTogetherUITests.swift" 'func test')
EXPECTED_UI_IPAD=$(count_matches "$ROOT/DinnerTogetherUITests/DinnerTogetherUITests_iPad.swift" 'func test')

note "# Native validation — $(date -u '+%Y-%m-%d %H:%M UTC')"
note ""
note "Project: $(basename "$ROOT") · bundle com.example.dinnertogether · scheme DinnerTogether · expected XCTest methods: $EXPECTED_TESTS · expected UI tests: $EXPECTED_UI_IPHONE (iPhone) + $EXPECTED_UI_IPAD (iPad)"
note ""

# ---------------------------------------------------------------- environment
{
  echo "== sw_vers";        sw_vers
  echo "== xcode-select";   xcode-select -p
  echo "== xcodebuild";     xcodebuild -version
  echo "== swift";          swift --version 2>&1
  echo "== simulators";     xcrun simctl list devices available
  echo "== runtimes";       xcrun simctl list runtimes available
} > "$RESULTS/environment.txt" 2>&1
note "## Environment"
note '```'
{ sw_vers | head -2; xcodebuild -version; } | tee -a "$SUMMARY"
note '```'
note ""

# ------------------------------------------------------------ pick simulators
pick_device() { # name-regex → "NAME|UDID" (newest iOS runtime; shortest matching name)
  xcrun simctl list devices available -j | python3 -c '
import json,sys,re
fam=sys.argv[1]
d=json.load(sys.stdin)["devices"]
cands=[]
for runtime,devs in d.items():
    if "iOS" not in runtime: continue
    for dev in devs:
        if dev.get("isAvailable") and re.search(fam, dev["name"]):
            cands.append((runtime, dev["name"], dev["udid"]))
cands.sort(key=lambda c:(c[0], -len(c[1])), reverse=True)
if cands: print(cands[0][1]+"|"+cands[0][2])
' "$1"
}
# DT_IPHONE_REGEX / DT_IPAD_REGEX override the device choice (the App Store
# screenshot workflow asks for the 6.9-inch iPhone and the 13-inch iPad).
IPHONE="$(pick_device "${DT_IPHONE_REGEX:-^iPhone [0-9]+$}" || true)"
[ -n "$IPHONE" ] || IPHONE="$(pick_device '^iPhone' || true)"
IPAD="$(pick_device "${DT_IPAD_REGEX:-^iPad}" || true)"
[ -n "$IPAD" ] || IPAD="$(pick_device '^iPad' || true)"
IPHONE_NAME="${IPHONE%%|*}"; IPHONE_UDID="${IPHONE##*|}"
IPAD_NAME="${IPAD%%|*}";     IPAD_UDID="${IPAD##*|}"
note "## Simulators (both required)"
if [ -n "$IPHONE_UDID" ]; then pass "iPhone simulator: $IPHONE_NAME"; else fail "no available iPhone simulator (see environment.txt)"; fi
if [ -n "$IPAD_UDID" ];   then pass "iPad simulator: $IPAD_NAME";     else fail "no available iPad simulator (see environment.txt)"; fi
note ""
# Quoted: simulator names contain spaces and parentheses ("iPad Pro 13-inch (M4)").
printf "IPHONE_NAME='%s'\nIPHONE_UDID='%s'\nIPAD_NAME='%s'\nIPAD_UDID='%s'\n" \
  "$IPHONE_NAME" "$IPHONE_UDID" "$IPAD_NAME" "$IPAD_UDID" > "$RESULTS/devices.env"

# ----------------------------------------------------------------- project
note "## Project"
LOG="$RESULTS/00-xcodebuild-list.log"
xcodebuild -list -project DinnerTogether.xcodeproj > "$LOG" 2>&1; rc=$?
step_result "xcodebuild -list (project parses, scheme visible)" $rc "$LOG"

# -------------------------------------------------------------------- build
DERIVED="$RESULTS/build"
COMMON=(-project DinnerTogether.xcodeproj -scheme DinnerTogether -configuration Debug -derivedDataPath "$DERIVED"
        CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY="")

note ""
note "## Build (required)"
APP_PATH=""
if [ -n "$IPHONE_UDID" ]; then
  LOG="$RESULTS/10-build-for-testing-iphone.log"
  xcodebuild build-for-testing "${COMMON[@]}" -destination "id=$IPHONE_UDID" > "$LOG" 2>&1; rc=$?
  step_result "build-for-testing app + test targets (iPhone simulator, Debug)" $rc "$LOG"
  if [ $rc -ne 0 ]; then
    note ""; note "First errors:"; note '```'
    grep -E 'error:|\*\* BUILD FAILED' "$LOG" | head -30 | tee -a "$SUMMARY"
    note '```'
  fi
  APP_PATH="$(find "$DERIVED/Build/Products" -maxdepth 2 -name 'DinnerTogether.app' -path '*iphonesimulator*' 2>/dev/null | head -1 || true)"
  # A failed build can still leave a partial .app directory behind (CI run 3):
  # require a successful build AND the executable inside the bundle.
  if [ $rc -eq 0 ] && [ -n "$APP_PATH" ] && [ -x "$APP_PATH/DinnerTogether" ]; then
    pass "simulator app present with executable: \`${APP_PATH#$RESULTS/}\`"
  else
    fail "no complete simulator app after build (build exit $rc; executable $([ -n "$APP_PATH" ] && [ -x "$APP_PATH/DinnerTogether" ] && echo present || echo missing))"
    APP_PATH=""
  fi
  # Confirm DEBUG reached the Swift compiler (needed by the screenshot launch flags).
  # Xcode 16 prints the condition as `-DDEBUG` (no space); older logs used `-D DEBUG`.
  if grep -qE -- '-D ?DEBUG' "$LOG" 2>/dev/null; then pass "Swift compiled with -DDEBUG (launch flags active)"; else fail "no '-DDEBUG' in the build log: #if DEBUG launch flags are compiled out"; fi
  # The Release configuration is what the archive compiles: a symbol that
  # exists only under #if DEBUG passes every Debug step here and fails the
  # release (build 9, release run 9: LaunchOptions.stubScreenshotData).
  LOG="$RESULTS/11-build-release-iphone.log"
  xcodebuild build -project DinnerTogether.xcodeproj -scheme DinnerTogether -configuration Release \
    -derivedDataPath "$DERIVED" -destination "id=$IPHONE_UDID" \
    CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY="" > "$LOG" 2>&1; rc=$?
  step_result "build app (iPhone simulator, Release — the configuration the archive compiles)" $rc "$LOG"
  if [ $rc -ne 0 ]; then
    note ""; note "First errors (Release):"; note '```'
    grep -E 'error:|\*\* BUILD FAILED' "$LOG" | head -30 | tee -a "$SUMMARY"
    note '```'
  fi
else
  fail "build skipped: no iPhone simulator"
fi
printf "APP_PATH='%s'\n" "$APP_PATH" >> "$RESULTS/devices.env"

# -------------------------------------------------------------------- tests
run_tests() { # label udid
  local label="$1" udid="$2"
  local bundle="$RESULTS/$label.xcresult"
  local log="$RESULTS/20-test-$label.log"
  local cases="$RESULTS/20-test-$label-cases.txt"
  rm -rf "$bundle"
  # Unit bundle only: without -only-testing the xctestrun also runs the UI
  # bundle here (run 14: "executed 72 (expected 61)"), double-running the
  # flows and mixing their failures into the unit verdict.
  xcodebuild test-without-building "${COMMON[@]}" -destination "id=$udid" \
    -only-testing:DinnerTogetherTests -resultBundlePath "$bundle" > "$log" 2>&1; rc=$?
  step_result "xcodebuild test-without-building on $label" $rc "$log"
  grep -E "Test Case '.*' (passed|failed)|Executed [0-9]+ tests" "$log" > "$cases" 2>/dev/null || true
  local passed failed executed skipped source
  # Prefer Xcode's structured result bundle (CI run 5: a simulator log line
  # interleaved with a "passed" line made the prose grep undercount by one).
  local summary="$RESULTS/20-test-$label-summary.json"
  if [ -d "$bundle" ]; then
    xcrun xcresulttool get test-results summary --path "$bundle" > "$summary" 2>/dev/null || rm -f "$summary"
  fi
  if [ -s "$summary" ] && counts=$(python3 -c 'import json,sys; j=json.load(open(sys.argv[1])); print(j["totalTestCount"], j["passedTests"], j["failedTests"], j.get("skippedTests", 0))' "$summary" 2>/dev/null); then
    set -- $counts; executed=$1; passed=$2; failed=$3; skipped=$4; source="xcresult"
  else
    passed=$(count_matches "$cases" "' passed")
    failed=$(count_matches "$cases" "' failed")
    skipped=$(count_matches "$log" "' skipped")
    executed=$(grep -oE 'Executed [0-9]+ tests' "$cases" 2>/dev/null | grep -oE '[0-9]+' | sort -n | tail -1)
    executed=${executed:-0}; source="log"
  fi
  note "  - cases on $label ($source): executed $executed (expected $EXPECTED_TESTS), passed $passed, failed $failed, skipped $skipped — \`$(basename "$cases")\`"
  if [ "$executed" -lt "$EXPECTED_TESTS" ]; then fail "$label executed $executed of $EXPECTED_TESTS expected tests"; fi
  if [ "$failed" -gt 0 ]; then
    fail "$label: $failed failing test case(s)"
    note '```'; grep "' failed" "$cases" | tee -a "$SUMMARY"; note '```'
    grep -E 'error:' "$log" | head -40 > "$RESULTS/20-test-$label-failures.txt" || true
  fi
  # A skipped test is a test that did not run; it cannot count toward "passed" (Agent 1, A1-4).
  if [ "$skipped" -gt 0 ]; then fail "$label: $skipped skipped test(s) — every test must execute"; fi
  if [ "$source" = "log" ] && [ "$passed" -lt "$executed" ] && [ "$failed" -eq 0 ] && [ "$skipped" -eq 0 ]; then
    note "    (note: $((executed - passed)) case line(s) unparsed in the log; xcresult summary was unavailable)"
  fi
  if [ -d "$bundle" ]; then
    (cd "$RESULTS" && zip -q -r "$label.xcresult.zip" "$(basename "$bundle")" && rm -rf "$bundle") || true
  fi
}

note ""
note "## XCTest (required; iPhone simulator — the iPad simulator runs the UI tests, A1 #19)"
if [ -n "$APP_PATH" ]; then
  if [ -n "$IPHONE_UDID" ]; then run_tests "iphone" "$IPHONE_UDID"; else fail "XCTest on iPhone skipped: no simulator"; fi
  # The unit tests are device-independent logic; the same binary ran on the
  # iPhone simulator a moment ago, on Linux and on macOS. The iPad simulator
  # runs the UI tests only (A1, issue #19: five minutes a cycle).
  note "  - cases on ipad: not run — the same test binary ran on the iPhone simulator above (A1 #19)"
else
  fail "XCTest skipped: app did not build"
fi

note ""
note "## XCUITest (required: interactive flows photographed)"
# Drives the real app in the simulator via the DinnerTogetherUITests target
# (seeded per-test through the DEBUG-only DT_SEED_JSON launch environment
# variable). Screenshots are keep-always XCTAttachments; they are exported
# from the result bundle so they publish to the ci-results branch next to
# the static screenshots.
run_ui_tests() { # label udid only_testing expected
  local label="$1" udid="$2" only_testing="$3" expected="$4"
  local bundle="$RESULTS/$label-ui.xcresult"
  local log="$RESULTS/25-ui-test-$label.log"
  rm -rf "$bundle"
  # Warm the simulator before XCTest asks it to launch the app: on a cold
  # boot the first flows time out waiting for launch progress (run
  # 38532632676: iPad test01–test03, "Timed out while requesting launch
  # progress", five minutes lost and a false failure). Boot, wait for the
  # boot to finish, install the app and launch it once, then let the tests
  # start against a simulator that has already run it. Best effort: a
  # warm-up problem is logged, never a verdict.
  {
    echo "== warm-up $label ($udid) $(date -u +%H:%M:%S)"
    xcrun simctl boot "$udid" 2>&1 || true
    xcrun simctl bootstatus "$udid" -b 2>&1 || true
    xcrun simctl install "$udid" "$APP_PATH" 2>&1 || true
    xcrun simctl launch "$udid" com.example.dinnertogether 2>&1 || true
    sleep "${DT_UI_WARMUP_SECONDS:-8}"
    xcrun simctl terminate "$udid" com.example.dinnertogether 2>&1 || true
    echo "== warm-up done $(date -u +%H:%M:%S)"
  } > "$RESULTS/24-ui-warmup-$label.log" 2>&1 || true
  # Per-test time allowance: a flow stuck on a missing element fails in
  # minutes instead of running the job into its timeout (run 12: 45 min).
  # XCTest allowances did not stop the 95-minute silent runner hang in
  # Duo run 38468245512. Bound the process independently and retain logs.
  python3 "$ROOT/native-validation/run-with-deadline.py" \
    --seconds 5400 --idle-seconds "${DT_UI_IDLE_SECONDS:-600}" -- \
    xcodebuild test-without-building "${COMMON[@]}" -destination "id=$udid" \
    -only-testing:"$only_testing" -resultBundlePath "$bundle" \
    -test-timeouts-enabled YES -default-test-execution-time-allowance 150 -maximum-test-execution-time-allowance 240 \
    > "$log" 2>&1; rc=$?
  local passed failed executed skipped source counts
  local summary="$RESULTS/25-ui-test-$label-summary.json"
  if [ -d "$bundle" ]; then
    xcrun xcresulttool get test-results summary --path "$bundle" > "$summary" 2>/dev/null || rm -f "$summary"
  fi
  local expectedfail=0
  if [ -s "$summary" ] && counts=$(python3 -c 'import json,sys; j=json.load(open(sys.argv[1])); print(j["totalTestCount"], j["passedTests"], j["failedTests"], j.get("skippedTests", 0), j.get("expectedFailures", 0))' "$summary" 2>/dev/null); then
    set -- $counts; executed=$1; passed=$2; failed=$3; skipped=$4; expectedfail=$5; source="xcresult"
  else
    executed=0; passed=0; failed=0; skipped=0; source="unavailable"
  fi
  # Up to three failing flows are run once more, alone (A1, issue #18: four
  # consecutive runs each failed on a different flow; a 90-minute cycle per
  # flake). A flaky pass is credited only when everything agrees (A1 #18,
  # A2-33: the first version could report green with a real failure):
  #   - every xcresult failure has a name from the log (complete identity),
  #   - the retry process exits 0,
  #   - the retry's own xcresult executed exactly those tests, all passed,
  #     none failed or skipped,
  #   - the retry log shows each test passed and none failed.
  # Anything else keeps the original failure verdict. A flaky pass is
  # reported in the summary, as an annotation and in FLAKY.txt — never hidden.
  local retried="" flaky="" stillfailing="" retrynote="" retrylog="$RESULTS/25-ui-test-$label-retry.log" retrybundle="$RESULTS/$label-ui-retry.xcresult"
  local credit=0
  # A killed process has incomplete evidence, even if a partial bundle
  # names failures. A retry must never turn a deadline into success.
  if [ "$rc" -ne 124 ] && [ "$failed" -gt 0 ] && [ "$failed" -le 3 ]; then
    local names namescount
    names=$(grep -oE "Test Case '-\[DinnerTogetherUITests\.[A-Za-z_]+ [A-Za-z0-9_]+\]' failed" "$log" \
      | sed -E "s/.*\.([A-Za-z_]+) ([A-Za-z0-9_]+)\]' failed/\1\/\2/" | sort -u)
    namescount=$(printf '%s' "$names" | wc -w | tr -d ' ')
    if [ "$namescount" -ne "$failed" ]; then
      echo "::warning title=retry-identity-$label::xcresult reports $failed failed UI test(s) but the log names $namescount — no retry credit possible (A2-33)"
      retrynote="the log named $namescount of $failed failures, so nothing was retried"
    elif [ -n "$names" ]; then
      local onlyargs=()
      for t in $names; do onlyargs+=("-only-testing:DinnerTogetherUITests/$t"); done
      rm -rf "$retrybundle"
      python3 "$ROOT/native-validation/run-with-deadline.py" \
        --seconds 900 --idle-seconds "${DT_UI_IDLE_SECONDS:-600}" -- \
        xcodebuild test-without-building "${COMMON[@]}" -destination "id=$udid" \
        "${onlyargs[@]}" -resultBundlePath "$retrybundle" \
        -test-timeouts-enabled YES -default-test-execution-time-allowance 150 -maximum-test-execution-time-allowance 240 \
        > "$retrylog" 2>&1; local retryrc=$?
      retried="$names"
      for t in $names; do
        local m="${t##*/}" c="${t%%/*}"
        if grep -qE "Test Case '-\[DinnerTogetherUITests\.$c $m\]' passed" "$retrylog" \
           && ! grep -qE "Test Case '-\[DinnerTogetherUITests\.$c $m\]' failed" "$retrylog"; then flaky="$flaky $t"; else stillfailing="$stillfailing $t"; fi
      done
      local rsummary="$RESULTS/25-ui-test-$label-retry-summary.json" rcounts rexec=0 rpass=0 rfail=1 rskip=0
      [ -d "$retrybundle" ] && { xcrun xcresulttool get test-results summary --path "$retrybundle" > "$rsummary" 2>/dev/null || rm -f "$rsummary"; }
      if [ -s "$rsummary" ] && rcounts=$(python3 -c 'import json,sys; j=json.load(open(sys.argv[1])); print(j["totalTestCount"], j["passedTests"], j["failedTests"], j.get("skippedTests", 0))' "$rsummary" 2>/dev/null); then
        set -- $rcounts; rexec=$1; rpass=$2; rfail=$3; rskip=$4
      fi
      local flakycount; flakycount=$(printf '%s' "$flaky" | wc -w | tr -d ' ')
      if [ "$retryrc" -eq 0 ] && [ -z "$stillfailing" ] && [ "$flakycount" -eq "$namescount" ] \
         && [ "$rexec" -eq "$namescount" ] && [ "$rpass" -eq "$namescount" ] && [ "$rfail" -eq 0 ] && [ "$rskip" -eq 0 ]; then
        credit=1
        printf '%s %s:%s\n' "$(date -u +%FT%TZ)" "$label" "$flaky" >> "$RESULTS/FLAKY.txt"
        retrynote="all $namescount passed alone (retry exit 0; retry xcresult $rexec executed, $rpass passed, $rfail failed, $rskip skipped)"
      else
        retrynote="no credit — retry exit $retryrc; log: passed [$flaky ], failed again [$stillfailing ]; retry xcresult $rexec executed, $rpass passed, $rfail failed, $rskip skipped"
      fi
    fi
  fi
  if [ "$credit" -eq 1 ]; then
    pass "xcodebuild UI tests on $label ($only_testing) (exit $rc on the first run; every failing flow passed alone on retry) — \`$(basename "$log")\`, \`$(basename "$retrylog")\`"
  else
    step_result "xcodebuild UI tests on $label ($only_testing)" $rc "$log"
  fi
  # The first failure, verbatim, so the summary says what broke without the log.
  grep -m1 -E 'error: -\[|XCTAssert|failed - ' "$log" | cut -c1-300 | sed 's/^/  - first failure: /' | tee -a "$SUMMARY" || true
  # Expected failures (XCTExpectFailure) are documented known issues; they are
  # reported here every run so they can never be forgotten, and never count as passes.
  note "  - UI cases on $label ($source): executed $executed (expected $expected), passed $passed, failed $failed, skipped $skipped, expected-failures $expectedfail — \`$(basename "$log")\`"
  if [ -n "$retrynote" ]; then
    note "  - retry on $label:$(printf ' %s' $retried) — $retrynote — \`$(basename "$retrylog")\`"
    if [ "$credit" -eq 1 ]; then for t in $flaky; do echo "::warning title=flaky-ui-$label::$t failed in the full run and passed alone on retry (see FLAKY.txt; A1 lane)"; done; fi
  fi
  if [ "$expectedfail" -gt 0 ]; then note "    - ⚠️ $expectedfail expected failure(s) on $label — known issue(s) documented in UITESTS.md; see the test's XCTExpectFailure message in \`$(basename "$log")\`"; fi
  if [ "$executed" -lt "$expected" ]; then fail "$label UI: executed $executed of $expected expected UI tests"; fi
  if [ "$credit" -eq 0 ] && [ "$failed" -gt 0 ]; then fail "$label UI: $failed failing UI test(s)$([ -n "$retried" ] && echo " (retry gave no credit:$stillfailing)")"; fi
  # A skipped test is a test that did not run; it cannot count toward "passed" (Agent 1, A1-4).
  if [ "$skipped" -gt 0 ]; then fail "$label UI: $skipped skipped UI test(s) — every test must execute"; fi
  local shots="$RESULTS/ui-screenshots/$label"
  rm -rf "$shots"; mkdir -p "$shots"
  local arc=0 pngs=0
  if [ -d "$bundle" ]; then
    xcrun xcresulttool export attachments --path "$bundle" --output-path "$shots" \
      > "$RESULTS/25-ui-test-$label-attachments.log" 2>&1; arc=$?
    # The retry's own renders, kept apart: the full run's failure state and
    # the retry's pass are both evidence.
    if [ -d "$retrybundle" ]; then
      mkdir -p "$shots/retry"
      xcrun xcresulttool export attachments --path "$retrybundle" --output-path "$shots/retry" \
        >> "$RESULTS/25-ui-test-$label-attachments.log" 2>&1 || true
    fi
  else
    arc=1
  fi
  if [ "$arc" -ne 0 ]; then
    fail "$label UI: attachment export failed (exit $arc) — the flows were not photographed"
  else
    # Best effort, never a gate: give the exported files their attachment
    # names (xcresulttool names them by UUID and describes them in
    # manifest.json), so Agent 2 can read "01-review-sheet.png" instead of a
    # hash. Unknown manifest shape → files keep their exported names. (A3-U-F7)
    for shotdir in "$shots" "$shots/retry"; do [ -d "$shotdir" ] || continue
    python3 - "$shotdir" >> "$RESULTS/25-ui-test-$label-attachments.log" 2>&1 <<'PY' || true
import json, os, sys
d = sys.argv[1]; m = os.path.join(d, "manifest.json")
try:
    entries = json.load(open(m))
except Exception as e:
    print("rename: no usable manifest.json (%s); exported names kept" % e); sys.exit(0)
seen = {}
for entry in (entries if isinstance(entries, list) else []):
    for att in entry.get("attachments", []) if isinstance(entry, dict) else []:
        src = att.get("exportedFileName"); want = att.get("suggestedHumanReadableName") or att.get("name")
        if not src or not want or not os.path.isfile(os.path.join(d, src)): continue
        ext = os.path.splitext(src)[1] or ".plist"   # extension-less exports are XCTest's own binary-plist attachments ("UI Snapshot", "Synthesized Event"); screenshots always arrive with .png
        import re
        want = re.sub(r"_\d+_[0-9A-Fa-f-]{36}(\.\w+)?$", "", want)   # "01-review-sheet_0_<UUID>.png" -> "01-review-sheet"
        want = re.sub(r"\.(png|txt|mp4|jpeg|jpg)$", "", want)
        base = "".join(c if c.isalnum() or c in "-_" else "-" for c in want)
        n = seen.get(base, 0) + 1; seen[base] = n
        dst = base + ("" if n == 1 else "-%d" % n) + ext
        os.rename(os.path.join(d, src), os.path.join(d, dst)); print("rename: %s -> %s" % (src, dst))
PY
    done
    # Count what was exported, whatever the extension: the attachments are
    # all screenshots, and a wrong guess about naming must not fail a run
    # whose flows were photographed. Zero files with tests executed still fails.
    pngs=$(find "$shots" -type f ! -name 'manifest.json' -size +0 2>/dev/null | wc -l | tr -d ' ')
    note "  - UI screenshots on $label: ${pngs:-0} file(s) under \`ui-screenshots/$label/\`"
    if [ "$executed" -gt 0 ] && [ "${pngs:-0}" -eq 0 ]; then
      fail "$label UI: $executed UI test(s) ran but no screenshots were exported"
    fi
  fi
  if [ -d "$bundle" ]; then
    (cd "$RESULTS" && zip -q -r "$label-ui.xcresult.zip" "$(basename "$bundle")" && rm -rf "$bundle") || true
  fi
  if [ -d "$retrybundle" ]; then
    (cd "$RESULTS" && zip -q -r "$label-ui-retry.xcresult.zip" "$(basename "$retrybundle")" && rm -rf "$retrybundle") || true
  fi
}

if [ -n "$APP_PATH" ]; then
