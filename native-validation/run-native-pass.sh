#!/usr/bin/env bash
# Native build + test pass for Dinner, Together. Runs on a GitHub macOS runner
# or any Mac with Xcode. It never stops at the first failure — every step
# records its exit code so the artifact tells the whole story — but it DOES
# exit non-zero at the end if any REQUIRED step failed or could not run
# (missing simulator, app not built, tests not executed, counts short).
#
#   bash native-validation/run-native-pass.sh [results-dir]
#
# Produces: <results>/SUMMARY.md, status.txt (REQUIRED_FAILURES=n),
# environment.txt, *.log, *-cases.txt, *.xcresult.zip, and the simulator app
# build for screenshots.sh under <results>/build.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RESULTS="${1:-$ROOT/native-validation/results}"
mkdir -p "$RESULTS"
cd "$ROOT"

SUMMARY="$RESULTS/SUMMARY.md"
STATUS="$RESULTS/status.txt"
: > "$SUMMARY"
REQUIRED_FAILURES=0
note() { printf '%s\n' "$*" | tee -a "$SUMMARY"; }
# count_matches FILE PATTERN → a single integer, never "0\n0"
count_matches() { local n; n=$(grep -c -- "$2" "$1" 2>/dev/null); printf '%s' "${n:-0}"; }
pass() { note "- ✅ $1"; }
fail() { note "- ❌ $1"; REQUIRED_FAILURES=$((REQUIRED_FAILURES + 1)); }
step_result() { # name exit_code logfile
  if [ "$2" -eq 0 ]; then pass "$1 (exit 0) — \`$(basename "$3")\`"; else fail "$1 (exit $2) — \`$(basename "$3")\`"; fi
}
finish() {
  printf 'REQUIRED_FAILURES=%s\n' "$REQUIRED_FAILURES" > "$STATUS"
  note ""
  if [ "$REQUIRED_FAILURES" -eq 0 ]; then
    note "**Result: all required steps passed.**"
  else
    note "**Result: $REQUIRED_FAILURES required step(s) failed or could not run.**"
  fi
  note ""
  note "_Generated by native-validation/run-native-pass.sh_"
  [ "$REQUIRED_FAILURES" -eq 0 ]
}

# Expected test count comes from the source, so "0 tests executed" cannot pass.
EXPECTED_TESTS=$(count_matches "$ROOT/DinnerTogetherTests/DinnerTogetherTests.swift" 'func test')

note "# Native validation — $(date -u '+%Y-%m-%d %H:%M UTC')"
note ""
note "Project: $(basename "$ROOT") · bundle com.example.dinnertogether · scheme DinnerTogether · expected XCTest methods: $EXPECTED_TESTS"
note ""

# ---------------------------------------------------------------- environment
{
  echo "== sw_vers";        sw_vers
  echo "== xcode-select";   xcode-select -p
  echo "== xcodebuild";     xcodebuild -version
  echo "== swift";          swift --version 2>&1
  echo "== simulators";     xcrun simctl list devices available
  echo "== runtimes";       xcrun simctl list runtimes available
} > "$RESULTS/environment.txt" 2>&1
note "## Environment"
note '```'
{ sw_vers | head -2; xcodebuild -version; } | tee -a "$SUMMARY"
note '```'
note ""

# ------------------------------------------------------------ pick simulators
pick_device() { # name-regex → "NAME|UDID" (newest iOS runtime; shortest matching name)
  xcrun simctl list devices available -j | python3 -c '
import json,sys,re
fam=sys.argv[1]
d=json.load(sys.stdin)["devices"]
cands=[]
for runtime,devs in d.items():
    if "iOS" not in runtime: continue
    for dev in devs:
        if dev.get("isAvailable") and re.search(fam, dev["name"]):
            cands.append((runtime, dev["name"], dev["udid"]))
cands.sort(key=lambda c:(c[0], -len(c[1])), reverse=True)
if cands: print(cands[0][1]+"|"+cands[0][2])
' "$1"
}
IPHONE="$(pick_device '^iPhone [0-9]+$' || true)"
[ -n "$IPHONE" ] || IPHONE="$(pick_device '^iPhone' || true)"
IPAD="$(pick_device '^iPad' || true)"
IPHONE_NAME="${IPHONE%%|*}"; IPHONE_UDID="${IPHONE##*|}"
IPAD_NAME="${IPAD%%|*}";     IPAD_UDID="${IPAD##*|}"
note "## Simulators (both required)"
if [ -n "$IPHONE_UDID" ]; then pass "iPhone simulator: $IPHONE_NAME"; else fail "no available iPhone simulator (see environment.txt)"; fi
if [ -n "$IPAD_UDID" ];   then pass "iPad simulator: $IPAD_NAME";     else fail "no available iPad simulator (see environment.txt)"; fi
note ""
# Quoted: simulator names contain spaces and parentheses ("iPad Pro 13-inch (M4)").
printf "IPHONE_NAME='%s'\nIPHONE_UDID='%s'\nIPAD_NAME='%s'\nIPAD_UDID='%s'\n" \
  "$IPHONE_NAME" "$IPHONE_UDID" "$IPAD_NAME" "$IPAD_UDID" > "$RESULTS/devices.env"

# ----------------------------------------------------------------- project
note "## Project"
LOG="$RESULTS/00-xcodebuild-list.log"
xcodebuild -list -project DinnerTogether.xcodeproj > "$LOG" 2>&1; rc=$?
step_result "xcodebuild -list (project parses, scheme visible)" $rc "$LOG"

# -------------------------------------------------------------------- build
DERIVED="$RESULTS/build"
COMMON=(-project DinnerTogether.xcodeproj -scheme DinnerTogether -configuration Debug -derivedDataPath "$DERIVED"
        CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY="")

note ""
note "## Build (required)"
APP_PATH=""
if [ -n "$IPHONE_UDID" ]; then
  LOG="$RESULTS/10-build-for-testing-iphone.log"
  xcodebuild build-for-testing "${COMMON[@]}" -destination "id=$IPHONE_UDID" > "$LOG" 2>&1; rc=$?
  step_result "build-for-testing app + test targets (iPhone simulator, Debug)" $rc "$LOG"
  if [ $rc -ne 0 ]; then
    note ""; note "First errors:"; note '```'
    grep -E 'error:|\*\* BUILD FAILED' "$LOG" | head -30 | tee -a "$SUMMARY"
    note '```'
  fi
  APP_PATH="$(find "$DERIVED/Build/Products" -maxdepth 2 -name 'DinnerTogether.app' -path '*iphonesimulator*' 2>/dev/null | head -1 || true)"
  # A failed build can still leave a partial .app directory behind (CI run 3):
  # require a successful build AND the executable inside the bundle.
  if [ $rc -eq 0 ] && [ -n "$APP_PATH" ] && [ -x "$APP_PATH/DinnerTogether" ]; then
    pass "simulator app present with executable: \`${APP_PATH#$RESULTS/}\`"
  else
    fail "no complete simulator app after build (build exit $rc; executable $([ -n "$APP_PATH" ] && [ -x "$APP_PATH/DinnerTogether" ] && echo present || echo missing))"
    APP_PATH=""
  fi
  # Confirm DEBUG reached the Swift compiler (needed by the screenshot launch flags).
  # Xcode 16 prints the condition as `-DDEBUG` (no space); older logs used `-D DEBUG`.
  if grep -qE -- '-D ?DEBUG' "$LOG" 2>/dev/null; then pass "Swift compiled with -DDEBUG (launch flags active)"; else fail "no '-DDEBUG' in the build log: #if DEBUG launch flags are compiled out"; fi
else
  fail "build skipped: no iPhone simulator"
fi
printf "APP_PATH='%s'\n" "$APP_PATH" >> "$RESULTS/devices.env"

# -------------------------------------------------------------------- tests
run_tests() { # label udid
  local label="$1" udid="$2"
  local bundle="$RESULTS/$label.xcresult"
  local log="$RESULTS/20-test-$label.log"
  local cases="$RESULTS/20-test-$label-cases.txt"
  rm -rf "$bundle"
  xcodebuild test-without-building "${COMMON[@]}" -destination "id=$udid" \
    -resultBundlePath "$bundle" > "$log" 2>&1; rc=$?
  step_result "xcodebuild test-without-building on $label" $rc "$log"
  grep -E "Test Case '.*' (passed|failed)|Executed [0-9]+ tests" "$log" > "$cases" 2>/dev/null || true
  local passed failed executed source
  # Prefer Xcode's structured result bundle (CI run 5: a simulator log line
  # interleaved with a "passed" line made the prose grep undercount by one).
  local summary="$RESULTS/20-test-$label-summary.json"
  if [ -d "$bundle" ]; then
    xcrun xcresulttool get test-results summary --path "$bundle" > "$summary" 2>/dev/null || rm -f "$summary"
  fi
  if [ -s "$summary" ] && counts=$(python3 -c 'import json,sys; j=json.load(open(sys.argv[1])); print(j["totalTestCount"], j["passedTests"], j["failedTests"])' "$summary" 2>/dev/null); then
    set -- $counts; executed=$1; passed=$2; failed=$3; source="xcresult"
  else
    passed=$(count_matches "$cases" "' passed")
    failed=$(count_matches "$cases" "' failed")
    executed=$(grep -oE 'Executed [0-9]+ tests' "$cases" 2>/dev/null | grep -oE '[0-9]+' | sort -n | tail -1)
    executed=${executed:-0}; source="log"
  fi
  note "  - cases on $label ($source): executed $executed (expected $EXPECTED_TESTS), passed $passed, failed $failed — \`$(basename "$cases")\`"
  if [ "$executed" -lt "$EXPECTED_TESTS" ]; then fail "$label executed $executed of $EXPECTED_TESTS expected tests"; fi
  if [ "$failed" -gt 0 ]; then
    fail "$label: $failed failing test case(s)"
    note '```'; grep "' failed" "$cases" | tee -a "$SUMMARY"; note '```'
    grep -E 'error:' "$log" | head -40 > "$RESULTS/20-test-$label-failures.txt" || true
  fi
  if [ "$passed" -lt "$executed" ] && [ "$failed" -eq 0 ]; then note "    (note: $((executed - passed)) case line(s) unparsed in the log; counts above come from $source)"; fi
  if [ -d "$bundle" ]; then
    (cd "$RESULTS" && zip -q -r "$label.xcresult.zip" "$(basename "$bundle")" && rm -rf "$bundle") || true
  fi
}

note ""
note "## XCTest (required on both simulators)"
if [ -n "$APP_PATH" ]; then
  if [ -n "$IPHONE_UDID" ]; then run_tests "iphone" "$IPHONE_UDID"; else fail "XCTest on iPhone skipped: no simulator"; fi
  if [ -n "$IPAD_UDID" ];   then run_tests "ipad"   "$IPAD_UDID";   else fail "XCTest on iPad skipped: no simulator"; fi
else
  fail "XCTest skipped: app did not build"
fi

# ------------------------------------------------- swift test (engine harness)
note ""
note "## swift test (Package.swift engine/store harness, macOS — required)"
LOG="$RESULTS/30-swift-test-macos.log"
swift test > "$LOG" 2>&1; rc=$?
step_result "swift test" $rc "$LOG"
executed=$(grep -oE 'Executed [0-9]+ tests' "$LOG" 2>/dev/null | grep -oE '[0-9]+' | sort -n | tail -1); executed=${executed:-0}
note "  - executed $executed (expected $EXPECTED_TESTS) — \`$(basename "$LOG")\`"
if [ "$executed" -lt "$EXPECTED_TESTS" ]; then fail "swift test executed $executed of $EXPECTED_TESTS expected tests"; fi
grep -E 'error:|failed' "$LOG" | head -20 | sed 's/^/    /' | tee -a "$SUMMARY" >/dev/null || true

note ""
note "## Not covered by this script"
note "- Real notification delivery, device behavior, VoiceOver reading order, haptics."
note "- Interactive flows (tapping Review dinner time); screenshots.sh covers static states only."
finish
